from collections import Counter
import json

# ΓöÇΓöÇ Config ΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇ
DATA_PATH = "data/research_paper/extracted_info/all_papers_structured.json"

# Example:
# "experiment_setup.compared_methods.name"
FIELD = "experiment_setup.compared_methods.name"

TOP_N = 40  # None for all

OUTPUT_FILE = f"{FIELD.replace('.', '_')}_counts.txt"
# ΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇ


def get_nested(obj, keys):
    """
    Traverse nested dict/list structure and return flat values.
    """
    if obj is None:
        return []

    if not keys:
        if isinstance(obj, list):
            return obj
        return [obj]

    key, rest = keys[0], keys[1:]

    if isinstance(obj, list):
        results = []
        for item in obj:
            results.extend(get_nested(item, keys))
        return results

    if isinstance(obj, dict):
        child = obj.get(key)
        if child is None:
            return []
        return get_nested(child, rest)

    return []


def extract_values(entry, field):
    """
    Extract values from dot-notation field path.
    """
    keys = field.split(".")
    raw = get_nested(entry, keys)

    flat = []
    for v in raw:
        if isinstance(v, list):
            flat.extend(v)
        else:
            flat.append(v)

    return [str(v) for v in flat if v not in (None, "", "None", "null")]


# ΓöÇΓöÇ Load data ΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇ
with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)

# ΓöÇΓöÇ Count values ΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇ
total_counts = Counter()

for entry in data:
    for v in extract_values(entry, FIELD):
        total_counts[v] += 1

# Apply TOP_N
if TOP_N is not None:
    sorted_items = total_counts.most_common(TOP_N)
else:
    sorted_items = total_counts.most_common()

# ΓöÇΓöÇ Save txt ΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇΓöÇ
with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
    f.write(f"Field: {FIELD}\n")
    f.write("=" * 80 + "\n\n")

    for rank, (name, count) in enumerate(sorted_items, start=1):
        f.write(f"{name}|{count}\n")

print(f"Saved counts to: {OUTPUT_FILE}")
